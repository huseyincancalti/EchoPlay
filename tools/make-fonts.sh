#!/usr/bin/env bash
# Regenerates app/fonts/: the three bundled UI fonts (OFL) as they are, and the icon font, Material Symbols Rounded
# (Apache-2.0), cut down from its ~10 MB variable file to the glyphs in app/fonts/icons.txt, one outlined and one
# filled static instance. Also writes app/qml/Icons.js (icon name -> character). Run it after adding a name to
# icons.txt. The results are committed: a normal build needs none of this.
# Needs: tools/setup-dev.sh (the venv, with fonttools).
# Usage: bash tools/make-fonts.sh
set -e
cd "$(dirname "$0")/.."
PY="$HOME/.echoplay-dev/venv/Scripts/python.exe"
"$PY" -m pip install -q --disable-pip-version-check fonttools
out=app/fonts
tmp=.out/fonts
mkdir -p "$out" "$tmp"

fetch() { [ -s "$2" ] || curl -fsSL "$1" -o "$2"; }

ofl=https://github.com/google/fonts/raw/main/ofl
fetch "$ofl/geist/Geist%5Bwght%5D.ttf" "$out/Geist.ttf"
fetch "$ofl/manrope/Manrope%5Bwght%5D.ttf" "$out/Manrope.ttf"
fetch "$ofl/plusjakartasans/PlusJakartaSans%5Bwght%5D.ttf" "$out/PlusJakartaSans.ttf"

ms=https://github.com/google/material-design-icons/raw/master/variablefont
fetch "$ms/MaterialSymbolsRounded%5BFILL,GRAD,opsz,wght%5D.ttf" "$tmp/ms.ttf"
fetch "$ms/MaterialSymbolsRounded%5BFILL,GRAD,opsz,wght%5D.codepoints" "$tmp/ms.codepoints"

"$PY" - "$tmp" "$out" <<'EOF'
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

tmp, out = sys.argv[1:]
codes = dict(line.split() for line in open(f"{tmp}/ms.codepoints"))
names = sorted({n.strip() for n in open(f"{out}/icons.txt") if n.strip()})
missing = [n for n in names if n not in codes]
if missing:
    sys.exit(f"not in Material Symbols: {missing}")
unicodes = [int(codes[n], 16) for n in names]

for fill, family, file in ((0, "EchoPlay Icons", "Icons.ttf"), (1, "EchoPlay Icons Filled", "IconsFilled.ttf")):
    font = instancer.instantiateVariableFont(TTFont(f"{tmp}/ms.ttf"), {"FILL": fill, "GRAD": 0, "opsz": 24, "wght": 400})
    options = subset.Options()
    options.layout_features = []  # the ligatures would pull in every icon
    options.name_IDs = ["*"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    for record in font["name"].names:
        if record.nameID in (1, 4, 16):
            record.string = family
        elif record.nameID == 6:
            record.string = family.replace(" ", "")
    font.save(f"{out}/{file}")

with open("app/qml/Icons.js", "w", newline="\n") as f:
    f.write("// Generated by tools/make-fonts.sh from app/fonts/icons.txt.\n.pragma library\n\nconst glyph = {\n")
    for n in names:
        f.write(f'    {n}: "\\u{codes[n]}",\n')
    f.write("}\n")
EOF
ls -la "$out"
