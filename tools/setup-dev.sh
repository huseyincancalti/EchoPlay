#!/usr/bin/env bash
# One-time dev toolchain for EchoPlay v2 on Windows. No admin rights, no Qt account.
# Installs into $ECHOPLAY_DEV (default ~/.echoplay-dev; not AppData, which some app sandboxes redirect):
#   venv/    Python venv with aqtinstall, cmake, ninja
#   qt/      Qt $QT_VERSION, MinGW kit, plus the matching MinGW compiler
#   libmpv/  libmpv dev package (zhongfly/mpv-winbuild, the same source v1's releases use)
# Then writes .out/devenv.sh, which tools/check.sh and the other tools source.
# Re-running is safe: finished parts are skipped. Usage: bash tools/setup-dev.sh
set -euo pipefail

QT_VERSION="${QT_VERSION:-6.10.3}"   # 6.11.x listing failed in aqt on 2026-10-29 (Updates.xml checksum)
QT_ARCH=win64_mingw
MINGW_TOOL=tools_mingw1310
MINGW_VARIANT=qt.tools.win64_mingw1310

cd "$(dirname "$0")/.."
DEV="$(cygpath -u "${ECHOPLAY_DEV:-$HOME/.echoplay-dev}")"
mkdir -p "$DEV" .out
PY="$DEV/venv/Scripts/python"

if [ ! -x "$PY" ]; then
  echo "venv: creating"
  python -m venv "$DEV/venv"
fi
"$PY" -m pip install -q --disable-pip-version-check aqtinstall cmake ninja
AQT="$DEV/venv/Scripts/aqt"

QT_DIR="$DEV/qt/$QT_VERSION/mingw_64"
if [ ! -f "$QT_DIR/bin/qmake.exe" ]; then
  echo "qt: installing $QT_VERSION $QT_ARCH"
  "$AQT" install-qt windows desktop "$QT_VERSION" "$QT_ARCH" -O "$DEV/qt"
fi

MINGW_DIR="$(ls -d "$DEV"/qt/Tools/mingw*_64 2>/dev/null | head -n 1 || true)"
if [ -z "$MINGW_DIR" ]; then
  echo "mingw: installing $MINGW_VARIANT"
  "$AQT" install-tool windows desktop "$MINGW_TOOL" "$MINGW_VARIANT" -O "$DEV/qt"
  MINGW_DIR="$(ls -d "$DEV"/qt/Tools/mingw*_64 | head -n 1)"
fi

# fetch_mpv <asset regex> <dir>: one asset of zhongfly's latest release, extracted into <dir>.
# libmpv/ is what v2 links; mpv/ is the same build as a plain player, the v1 baseline for tools/bench.sh.
fetch_mpv() {
  local url
  url=$(curl -fsSL https://api.github.com/repos/zhongfly/mpv-winbuild/releases/latest \
    | grep -oE "\"browser_download_url\": *\"[^\"]*/$1\"" | head -n 1 | sed -E 's/.*"(https[^"]+)"/\1/')
  [ -n "$url" ] || { echo "no asset matching $1"; exit 1; }
  curl -fsSL -o "$DEV/download.7z" "$url"
  rm -rf "$2" && mkdir -p "$2"
  if command -v 7z >/dev/null 2>&1; then
    7z x -y -o"$2" "$DEV/download.7z" >/dev/null
  else
    [ -f "$DEV/7zr.exe" ] || curl -fsSL -o "$DEV/7zr.exe" https://www.7-zip.org/a/7zr.exe
    "$DEV/7zr.exe" x -y -o"$2" "$DEV/download.7z" >/dev/null
  fi
  rm -f "$DEV/download.7z"
  echo "$url" > "$2/SOURCE.txt"
}
[ -f "$DEV/libmpv/include/mpv/client.h" ] || { echo "libmpv: downloading"; fetch_mpv 'mpv-dev-x86_64-[0-9][^"]*\.7z' "$DEV/libmpv"; }
[ -f "$DEV/mpv/mpv.exe" ] || { echo "mpv: downloading"; fetch_mpv 'mpv-x86_64-[0-9][^"]*\.7z' "$DEV/mpv"; }

DPI=$(powershell -NoProfile -Command "(Get-ItemProperty 'HKCU:\Control Panel\Desktop\WindowMetrics' -ErrorAction SilentlyContinue).AppliedDPI" | tr -d '\r')
DPI="${DPI:-96}"
cat > .out/devenv.sh <<EOF
# Generated by tools/setup-dev.sh. Source it: . .out/devenv.sh
export ECHOPLAY_DEV="$(cygpath -m "$DEV")"
export PATH="$DEV/venv/Scripts:$QT_DIR/bin:$MINGW_DIR/bin:$DEV/libmpv:\$PATH"
export CMAKE_PREFIX_PATH="$(cygpath -m "$QT_DIR")"
export MPV_DIR="$(cygpath -m "$DEV/libmpv")"
export MPV_EXE="$DEV/mpv/mpv.exe"
export CMAKE_GENERATOR=Ninja
# v2's 1280x720 logical window in physical pixels (Qt applies Windows display scaling; mpv's --geometry does not)
export V1_GEOMETRY="$((1280 * DPI / 96))x$((720 * DPI / 96))"
EOF

echo "ready: Qt $QT_VERSION, $(basename "$MINGW_DIR"), libmpv from $(cat "$DEV/libmpv/SOURCE.txt" | sed 's#.*/##')"
echo "env:   .out/devenv.sh"
